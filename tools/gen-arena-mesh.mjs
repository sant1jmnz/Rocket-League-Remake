// Generates packages/shared/src/arena/meshdata.ts from the standard (soccar) collision meshes
// shipped with rl_ball_sym (MIT, https://github.com/VirxEC/rl_ball_sym, assets/standard).
//
//   git clone --depth 1 https://github.com/VirxEC/rl_ball_sym /tmp/rl_ball_sym
//   node tools/gen-arena-mesh.mjs /tmp/rl_ball_sym/assets/standard
//
// Triangles are re-wound so that their normals point into the playable space (the source winding
// is not consistent); the arena module mirrors each piece into the four quadrants at load time.
/* global console */
import { Buffer } from 'node:buffer';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node tools/gen-arena-mesh.mjs <rl_ball_sym/assets/standard>');

const read = (file, Type) => {
  const b = fs.readFileSync(path.join(dir, file));
  return new Type(b.buffer.slice(b.byteOffset, b.byteOffset + b.length));
};

// Rough inside test for orienting the triangles: the field box with cut corners and the goal boxes.
function insideScore(x, y, z) {
  const ax = Math.abs(x);
  const ay = Math.abs(y);
  let d = Math.min(4096 - ax, 5120 - ay, (8064 - ax - ay) / Math.SQRT2, z, 2044 - z);
  if (ay > 4900) d = Math.max(d, Math.min(893 - ax, 6000 - ay, z, 643 - z));
  return d;
}

const PIECES = [
  ['corner', 'standard_corner', 0],
  ['goal', 'standard_goal', -5120],
  ['ramps0', 'standard_ramps_0', 0],
  ['ramps1', 'standard_ramps_1', 0],
];

const out = [];
for (const [key, name, yOff] of PIECES) {
  const ids = read(`${name}_ids.bin`, Int32Array);
  const v = read(`${name}_vertices.bin`, Float32Array);
  const fixed = new Uint16Array(ids.length);
  let flipped = 0;
  for (let t = 0; t < ids.length; t += 3) {
    const [a, b, c] = [ids[t], ids[t + 1], ids[t + 2]];
    const P = (i) => [v[i * 3], v[i * 3 + 1] + yOff, v[i * 3 + 2]];
    const [pa, pb, pc] = [P(a), P(b), P(c)];
    const e1 = pb.map((x, k) => x - pa[k]);
    const e2 = pc.map((x, k) => x - pa[k]);
    const n = [e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]];
    const l = Math.hypot(...n) || 1;
    const cen = [0, 1, 2].map((k) => (pa[k] + pb[k] + pc[k]) / 3);
    const s = 30;
    const front = insideScore(...cen.map((x, k) => x + (n[k] / l) * s));
    const back = insideScore(...cen.map((x, k) => x - (n[k] / l) * s));
    const flip = back > front;
    if (flip) flipped++;
    fixed.set(flip ? [a, c, b] : [a, b, c], t);
  }
  console.log(`${name}: ${ids.length / 3} triangles, ${v.length / 3} vertices, ${flipped} re-wound`);
  out.push({ key, verts: Buffer.from(v.buffer).toString('base64'), ids: Buffer.from(fixed.buffer).toString('base64'), yOff });
}

let ts = `// GENERATED by tools/gen-arena-mesh.mjs — do not edit.
// Standard arena collision meshes (one quadrant of each piece) from rl_ball_sym
// (MIT, Copyright (c) 2023 VirxEC, https://github.com/VirxEC/rl_ball_sym), originally extracted
// from Rocket League by the RLUtilities project. Vertices: float32 little-endian xyz; ids: uint16
// triangles wound so the normals point into the playable space.

export interface MeshPiece {
  /** translation applied along y before mirroring */
  yOffset: number;
  verts: string;
  ids: string;
}

export const ARENA_MESH_PIECES: Record<'corner' | 'goal' | 'ramps0' | 'ramps1', MeshPiece> = {
`;
for (const p of out) ts += `  ${p.key}: {\n    yOffset: ${p.yOff},\n    verts:\n      '${p.verts}',\n    ids:\n      '${p.ids}',\n  },\n`;
ts += '};\n';
fs.writeFileSync('packages/shared/src/arena/meshdata.ts', ts);
